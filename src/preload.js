const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  pickFiles: (lang) => ipcRenderer.invoke('pick-files', lang),
  inspect: (paths) => ipcRenderer.invoke('inspect', paths),
  probe: (file, opts) => ipcRenderer.invoke('probe', file, opts),
  thumb: (job) => ipcRenderer.invoke('thumb', job),
  subFiles: (file) => ipcRenderer.invoke('sub-files', file),
  subtitles: (job) => ipcRenderer.invoke('subtitles', job),
  pickSub: (lang) => ipcRenderer.invoke('pick-sub', lang),
  saveList: (job) => ipcRenderer.invoke('save-list', job),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  onTop: (on) => ipcRenderer.invoke('on-top', on),
  brawLook: (l) => ipcRenderer.invoke('braw-look', l),
  setDefault: (job) => ipcRenderer.invoke('set-default', job),
  defaultStatus: (exts) => ipcRenderer.invoke('default-status', exts),
  fileKinds: () => ipcRenderer.invoke('file-kinds'),
  stream: (job) => ipcRenderer.invoke('stream', job),
  stop: (ids) => ipcRenderer.invoke('stop', ids),
  waveform: (job) => ipcRenderer.invoke('waveform', job),
  cover: (file) => ipcRenderer.invoke('cover', file),
  snapshot: (job) => ipcRenderer.invoke('snapshot', job),
  reveal: (file) => ipcRenderer.invoke('reveal', file),
  copy: (text) => ipcRenderer.invoke('copy', text),
  fit: (job) => ipcRenderer.invoke('fit', job),
  compact: (on) => ipcRenderer.invoke('compact', on),
  platform: () => ipcRenderer.invoke('platform'),
  version: () => ipcRenderer.invoke('version'),
  title: (t) => ipcRenderer.invoke('title', t),
  pathForFile: (f) => webUtils.getPathForFile(f),
  onOpenFiles: (cb) => ipcRenderer.on('open-files', (_e, list) => cb(list)),
  onStreamError: (cb) => ipcRenderer.on('stream-error', (_e, d) => cb(d)),
  packets: (job) => ipcRenderer.invoke('packets', job),
  qc: (job) => ipcRenderer.invoke('qc', job),
  onScanProgress: (cb) => ipcRenderer.on('scan-progress', (_e, d) => cb(d)),
  onQcProgress: (cb) => ipcRenderer.on('qc-progress', (_e, d) => cb(d)),
  pickLut: () => ipcRenderer.invoke('pick-lut'),
  readLut: (file) => ipcRenderer.invoke('read-lut', file),
  pickOne: (lang) => ipcRenderer.invoke('pick-one', lang),
  saveText: (job) => ipcRenderer.invoke('save-text', job),
  update: {
    state: () => ipcRenderer.invoke('rp:update-state'),
    check: () => ipcRenderer.invoke('rp:update-check'),
    install: () => ipcRenderer.invoke('rp:update-install'),
    auto: (on) => ipcRenderer.invoke('rp:update-auto', on),
    on: (cb) => ipcRenderer.on('rp:update', (_e, s) => cb(s)),
  },
});
